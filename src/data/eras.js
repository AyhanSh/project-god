export function getEraForYear(year) {
  for (let i = ERAS.length - 1; i >= 0; i--) {
    if (year >= ERAS[i].startYear) return ERAS[i]
  }
  return ERAS[0]
}

export function getEraIndex(eraId) {
  return ERAS.findIndex((e) => e.id === eraId)
}
